export function generate90DaysWasteHistory(): DailyWasteRecord[] {
  const records: DailyWasteRecord[] = [];
  const hospitals = SEED_HOSPITALS.slice(0, 8);
  const now = new Date('2026-09-10T00:00:00Z');

  for (let d = 90; d >= 0; d--) {
    const day = new Date(now.getTime() - d * 24 * 60 * 60 * 1000);
    const dateStr = day.toISOString().split('T')[0];

    for (const hosp of hospitals) {
      const baseBedRatio = (hosp.bedCapacity || 200) / 100;
      // Realistic day variance
      const dayFactor = 0.8 + ((day.getDay() * 7 + (hosp.hospitalId.charCodeAt(5) % 10)) % 40) / 100;

      const yellow = Number((12.5 * baseBedRatio * dayFactor).toFixed(1));
      const red = Number((9.8 * baseBedRatio * dayFactor).toFixed(1));
      const white = Number((2.4 * baseBedRatio * dayFactor).toFixed(1));
      const blue = Number((1.9 * baseBedRatio * dayFactor).toFixed(1));
      const total = Number((yellow + red + white + blue).toFixed(1));

      records.push({
        recordId: `hist-${hosp.hospitalId}-${dateStr}`,
        hospitalId: hosp.hospitalId,
        hospitalName: hosp.name,
        date: dateStr,
        yellowKg: yellow,
        redKg: red,
        whiteKg: white,
        blueKg: blue,
        totalKg: total,
        dataType: 'SYNTHETIC_DEMO_WASTE_DATA',
      });
    }
  }

  return records;
}

